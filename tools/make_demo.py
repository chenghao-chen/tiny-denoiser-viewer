#!/usr/bin/env python3
"""Generate a tiny synthetic demo collection so the viewer can be tried.

Standard library plus Pillow. Writes only content/demo/. Delete that
folder and re-run scan.py to remove it again.

    python tools/make_demo.py && python tools/scan.py
"""

from __future__ import annotations

import argparse
import csv
import json
import math
import random
from pathlib import Path

from PIL import Image

HERE = Path(__file__).resolve().parent
VIEWER = HERE.parent

W = H = 192
METHODS = ["alpha_net", "beta_net", "gamma_net", "delta_net"]
VARIANTS = ["10k", "50k", "250k", "1m"]
SCENES = {
    "scene_rings": dict(tags=["synthetic", "edges"],
                        caption="Concentric rings: an easy test of ringing."),
    "scene_grid":  dict(tags=["synthetic", "texture"],
                        caption="Chequerboard and gradient: tests texture loss."),
}


def reference(kind: str) -> Image.Image:
    im = Image.new("L", (W, H))
    px = im.load()
    for y in range(H):
        for x in range(W):
            if kind == "scene_rings":
                r = math.hypot(x - W / 2, y - H / 2)
                v = 128 + 110 * math.sin(r / 6.0)
            else:
                checker = ((x // 12) + (y // 12)) % 2
                v = 40 + 170 * checker * (0.35 + 0.65 * x / W)
            px[x, y] = max(0, min(255, int(v)))
    return im


def degrade(ref: Image.Image, noise: float, blur: float,
            rng: random.Random) -> Image.Image:
    """Blur by averaging a shifted copy, then add noise. Deliberately crude."""
    src = ref.load()
    out = Image.new("L", (W, H))
    dst = out.load()
    k = max(0, int(blur))
    for y in range(H):
        for x in range(W):
            if k:
                acc = n = 0
                for dy in range(-k, k + 1):
                    for dx in range(-k, k + 1):
                        xx, yy = min(W - 1, max(0, x + dx)), min(H - 1, max(0, y + dy))
                        acc += src[xx, yy]; n += 1
                v = acc / n
            else:
                v = src[x, y]
            v += rng.gauss(0.0, noise)
            dst[x, y] = max(0, min(255, int(v)))
    return out


def psnr(a: Image.Image, b: Image.Image) -> float:
    pa, pb = a.load(), b.load()
    se = 0
    for y in range(H):
        for x in range(W):
            d = pa[x, y] - pb[x, y]
            se += d * d
    mse = se / (W * H) / (255.0 ** 2)
    return 99.0 if mse <= 0 else 10.0 * math.log10(1.0 / mse)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--content", type=Path, default=VIEWER / "content")
    args = ap.parse_args(argv)

    root = args.content / "demo"
    root.mkdir(parents=True, exist_ok=True)
    (root / "collection.json").write_text(json.dumps({
        "group": "Demo",
        "label": "synthetic demo",
        "caption": ("Synthetic demo content generated by tools/make_demo.py. "
                    "Delete content/demo/ and re-run tools/scan.py to remove "
                    "it. Nothing here comes from a real dataset or model."),
        "order": 999,
    }, indent=2) + "\n")
    (root / "variants.json").write_text(json.dumps({
        "1m": {"label": "1M", "badge": "largest"},
    }, indent=2) + "\n")

    rng = random.Random(0)
    curves = [["method", "variant", "value"]]
    for scene, info in SCENES.items():
        sdir = root / scene
        sdir.mkdir(exist_ok=True)
        ref = reference(scene)
        ref.save(sdir / "_reference.png")
        noisy = degrade(ref, noise=22.0, blur=0, rng=rng)
        noisy.save(sdir / "_input.png")
        ref.resize((96, 96), Image.NEAREST).save(sdir / "_thumb.png")
        (sdir / "scene.json").write_text(json.dumps({
            "tags": info["tags"], "caption": info["caption"],
            "meta": {"source": "synthetic"},
        }, indent=2) + "\n")

        rows = [["method", "variant", "psnr"], ["_input", "", f"{psnr(noisy, ref):.2f}"]]
        for mi, method in enumerate(METHODS):
            mdir = sdir / method
            mdir.mkdir(exist_ok=True)
            for vi, variant in enumerate(VARIANTS):
                # bigger variants denoise better; methods differ a little
                noise = 14.0 - 3.0 * vi - 0.8 * mi
                blur = 1 if (mi % 2 == 0 and vi < 2) else 0
                img = degrade(ref, noise=max(1.0, noise), blur=blur, rng=rng)
                img.save(mdir / f"{variant}.png")
                rows.append([method, variant, f"{psnr(img, ref):.2f}"])
        with (sdir / "metrics.csv").open("w", newline="") as fh:
            csv.writer(fh).writerows(rows)

    # A dataset-level curve: the mean over the two scenes.
    for method in METHODS:
        for variant in VARIANTS:
            vals = []
            for scene in SCENES:
                with (root / scene / "metrics.csv").open() as fh:
                    for r in csv.DictReader(fh):
                        if r["method"] == method and r["variant"] == variant:
                            vals.append(float(r["psnr"]))
            if vals:
                curves.append([method, variant, f"{sum(vals)/len(vals):.2f}"])
    with (root / "curves.csv").open("w", newline="") as fh:
        csv.writer(fh).writerows(curves)

    print(f"wrote {root} ({len(SCENES)} scenes, {len(METHODS)} methods, "
          f"{len(VARIANTS)} variants)")
    print("now run: python tools/scan.py")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
